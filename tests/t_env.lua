local function host(path) local f = assert(H.hostloadfile(path)) return f() end
local C = host(HARNESS_DIR .. "/common.lua")
C.stage(REPO .. "/NyxOS/data/lib", "lib")
C.stage(REPO .. "/NyxOS/data/bin", "bin")
C.stage(REPO .. "/NyxOS/data/etc", "etc")
local f = fs.open("etc/passwd", "w") f.write(textutils.serialize({{username="alice",password="",home="/home/alice",admin=true}})) f.close()
fs.makeDir("home/alice") fs.makeDir("var/run") fs.makeDir("var/swap")
local nyxlib = dofile("/lib/nyxlib.lua") nyxlib.saveSession("alice")
f = fs.open("etc/environment","w") f.write("# global\nEDITOR=nano\nGREETING=\"hello world\"\n") f.close()
local env = dofile("/lib/env.lua")
H.say("EDITOR", env.get("EDITOR"), "GREETING", env.get("GREETING"), "HOME", env.get("HOME"), "USER", env.get("USER"))
env.set("X","42")
H.say("expand:", env.expand("echo $X ${GREETING} ~/f \\$X $NOPE end"))
H.say("persist", env.persist("COLOR","red"), fs.exists("home/alice/.profile") and (function() local g=fs.open("home/alice/.profile","r") local t=g.readAll() g.close() return t end)())
H.say("persist rm", env.persist("COLOR",nil))
shell = { dir=function() return "" end, path=function() return "/bin" end, resolve=function(p) return p end,
  run=function(cmd) local w={} for x in cmd:gmatch("%S+") do w[#w+1]=x end local f=assert(loadfile("/bin/"..w[1]..".lua")) f(table.unpack(w,2)) return true end }
local cap = dofile("/lib/capture.lua")
H.say("capture:", cap.run("echo value=$X"))
H.say("capture export:", cap.run("export Y=7"), cap.run("echo y=$Y"))
local vm = dofile("/lib/vm.lua")
local h, e = vm.alloc(10000)
H.say("alloc", h, e)
H.say("write", vm.write(h, 1, "hello"), vm.write(h, 2040, "ACROSS-PAGE-BOUNDARY"), vm.write(h, 9990, "tail-data!"))
H.say("read", vm.read(h,1,5), vm.read(h,2040,20), vm.read(h,9990,10), #vm.read(h,1,10000))
H.say("range", vm.read(h, 9995, 10))
-- force eviction
for i=1,6 do vm.write(h, i*1500, "p"..i) end
vm.sync()
H.say("after evict", vm.read(h,1,5), vm.read(h,1500,2), vm.read(h,9000,2))
local s = vm.stats()
H.say("stats", s.blocks, s.bytes, s.cached, s.cacheMax, s.hits, s.misses)
H.say("free:", cap.run("free"))
vm.free(h)
H.say("freed", vm.stats().blocks, fs.exists("var/swap/"..h))
